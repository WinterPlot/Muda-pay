object AppLanguage {
    private var appContext: Context? = null
    var current by mutableStateOf("en")
        private set
    fun init(context: Context) {
        appContext = context.applicationContext
        current = appContext!!.getSharedPreferences("mudapay_language", Context.MODE_PRIVATE).getString("language", "en") ?: "en"
    }
    fun set(language: String) {
        current = if (language == "fr") "fr" else "en"
        appContext?.getSharedPreferences("mudapay_language", Context.MODE_PRIVATE)?.edit()?.putString("language", current)?.apply()
    }
}
